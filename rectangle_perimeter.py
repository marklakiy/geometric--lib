def rectangle_perimeter(a, b):
    '''
    Принимает стороны a и b, возвращает периметр прямоугольника.

    Параметры:
        a (int/float): длина первой стороны.
        b (int/float): длина второй стороны.
    
    Возвращаемое значение:
        (int/float): периметр прямоугольника (2a + 2b).
    '''
    return 2 * a + 2 * b