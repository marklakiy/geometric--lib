def rectangle_area(a, b):
    '''
    Принимает стороны a и b, возвращает площадь прямоугольника

    Параметры:
        a (int/float): длина первой стороны
        b (int/float): длина второй стороны
    
    Возвращаемое значение:
        (int/float): площадь прямоугольника (a * b)
    
    '''
    return a * b
